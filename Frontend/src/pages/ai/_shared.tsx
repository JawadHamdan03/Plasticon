// ── Severity badge ─────────────────────────────────────────────────────────────
export function SeverityBadge({ level }: { level: "HIGH" | "MEDIUM" | "LOW" }) {
  const map = {
    HIGH:   { bg: "#fee2e2", color: "#dc2626", label: "High" },
    MEDIUM: { bg: "#fef3c7", color: "#d97706", label: "Medium" },
    LOW:    { bg: "#dcfce7", color: "#16a34a", label: "Low" },
  };
  const { bg, color, label } = map[level];
  return (
    <span style={{ padding: ".2rem .55rem", borderRadius: 999, fontSize: ".7rem", fontWeight: 700, background: bg, color, letterSpacing: ".03em" }}>
      {label}
    </span>
  );
}
