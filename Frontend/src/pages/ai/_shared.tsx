// ── Action button ─────────────────────────────────────────────────────────────
export function AIButton({ gradient, onClick, disabled, loading, loadingText = "Processing…", icon: Icon, children }: {
  gradient: [string, string]; onClick: () => void; disabled?: boolean; loading?: boolean;
  loadingText?: string; icon?: React.ComponentType<{ size?: number }>; children: React.ReactNode;
}) {
  const [from, to] = gradient;
  const off = disabled || loading;
  return (
    <button type="button" onClick={onClick} disabled={off} style={{ padding: ".65rem 1.4rem", border: "none", borderRadius: 9, cursor: off ? "default" : "pointer", background: off ? "var(--bg-subtle)" : `linear-gradient(135deg, ${from}, ${to})`, color: off ? "var(--text-muted)" : "#fff", fontWeight: 700, fontSize: ".88rem", display: "flex", alignItems: "center", justifyContent: "center", gap: ".45rem", boxShadow: off ? "none" : `0 3px 10px ${from}40`, letterSpacing: ".01em", whiteSpace: "nowrap" as const, transition: "box-shadow .15s" }}>
      {loading ? <><RotateCcw size={15} style={{ animation: "spin 1s linear infinite" }} />{loadingText}</> : <>{Icon && <Icon size={15} />}{children}</>}
    </button>
  );
}

